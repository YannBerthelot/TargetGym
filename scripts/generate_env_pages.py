from target_gym.units import param_units  # noqa: E402

OUT_DIR = ROOT / "docs" / "environments"
CHOOSER = ROOT / "docs" / "complexity.md"
CHOOSER_BEGIN = "<!-- BEGIN table generated by scripts/generate_env_pages.py -->"
CHOOSER_END = "<!-- END generated table -->"
# The recorded baselines, from where the package reads them. This used to be
# a path of its own, ``data/baseline_returns.json`` at the repository root,
# which stopped existing when the data moved into the package. The generator
# checked ``exists()`` and fell back to a sentence, so every page quietly lost
# its numbers and ``--check`` still passed. It refuses an empty record now: if
# the data moves again, this script fails instead of degrading.

# Where each environment's gif lives, relative to the repository root. Only
# environments with a rendered clip get a picture; the rest simply omit it.
VIDEO_CANDIDATES = ("videos/{name}/pid_output.gif",)
# One candidate, deliberately: whatever ``target_gym.runners.runners`` writes.
#
# This used to prefer a hand-placed ``*_short.gif`` and fall back to the
# generated clip, and the comment here already recorded that going wrong once --
# "the gallery showed pre-re-skin aircraft for a week". It went wrong the same
# way a second time. Thirteen pages were still showing shorts that no generator
# refreshes, so after the aircraft renderers were unified the gallery was split
# between two visual styles, and the glass furnace's short played for 1.8 s
# against the 9.8 s of every regenerated clip.
#
# A fallback chain whose first entry nothing maintains is a trap, so there is no
# chain now. If a page has no picture, that is because no clip was rendered for
# it, which is a fact worth seeing rather than papering over.
SPECIAL_VIDEOS: dict[str, str] = {}


def _video(name: str) -> str | None:
    """The clip path for *name*, without checking whether the file is there.

    It deliberately does not test for existence. The clips are a build artifact:
    ``.gitignore`` excludes ``videos/**/*.gif`` and the docs-deploy workflow
    renders them before mkdocs runs, so they are present on the published site
    and absent from a clean checkout. Branching on presence made these pages
    depend on whether the generator happened to run on a machine that had them,
    which is exactly what CI caught: pages committed from a working tree with
    clips disagreed with pages generated in CI without them, and all twenty-one
    came back stale.
    """
    for candidate in (
        SPECIAL_VIDEOS.get(name),
        *(c.format(name=name) for c in VIDEO_CANDIDATES),
    ):
        if candidate:
            return candidate
    return None


def _first_paragraph(doc: str | None) -> str:
    if not doc:
        return ""
    out: list[str] = []
    for line in doc.strip().splitlines():
        if not line.strip() and out:
            break
        out.append(line.strip())
    return " ".join(out)


_BLOCK = re.compile(r"^### (Task|Observation): (.+)$")
_OBS_HEADER = re.compile(r"^\|\s*obs\s*\|\s*meaning\s*\|\s*$")
_OBS_ROW = re.compile(r"^\|\s*(\d+)(?:-(\d+))?\s*\|\s*(.*?)\s*\|\s*$")


def _obs_rows(body: list[str]) -> list[tuple[int, int, str]]:
    for k, line in enumerate(body):
        if _OBS_HEADER.match(line):
            rows = []
            for row in body[k + 2 :]:
                m = _OBS_ROW.match(row)
                if not m:
                    break
                first = int(m.group(1))
                rows.append((first, int(m.group(2) or first), m.group(3)))
            return rows
    return []


def task_blocks(path: pathlib.Path) -> dict[str, dict]:
    """Each task's summary paragraph and observation rows, from its contract.

    A ``### Task: `name``` subsection opens with the paragraph the task's page
    leads with. A ``| obs | meaning |`` table names every observation index,
    one row per index or ``i-j`` range; it sits in the task's own subsection
    or, for tasks that share a layout, in one ``### Observation: `a`, `b```
    subsection.
    """
    found: dict[str, dict] = {}
    lines = path.read_text().splitlines()
    for i, heading in enumerate(lines):
        m = _BLOCK.match(heading)
        if not m:
            continue
        body = []
        for line in lines[i + 1 :]:
            if re.match(r"^#{1,3} ", line):
                break
            body.append(line)
        entry = {"obs": _obs_rows(body)} if _obs_rows(body) else {}
        if m.group(1) == "Task":
            entry["summary"] = _first_paragraph("\n".join(body))
        for name in re.findall(r"`(\w+)`", m.group(2)):
            for key, value in entry.items():
                if key in found.setdefault(name, {}):
                    raise SystemExit(f"{path}: two {key} blocks for `{name}`")
                found[name][key] = value
    return found


def _task_block(name: str, env, n_obs: int) -> dict:
    """*name*'s block, checked: a summary, and one row for every index."""
    path = ROOT / physics_path(env)
    block = task_blocks(path).get(name, {})
    if not block.get("summary") or block["summary"].startswith("|"):
        raise SystemExit(f"{path}: no `### Task: `{name}`` paragraph")
    if "obs" not in block:
        raise SystemExit(f"{path}: no `| obs | meaning |` table for `{name}`")
    expected = 0
    for first, last, _ in block["obs"]:
        if first != expected or last < first:
            raise SystemExit(
                f"{path}: `{name}` observation rows must run from 0 in order; "
                f"found {first}-{last} where {expected} was next"
            )
        expected = last + 1
    if expected != n_obs:
        raise SystemExit(
            f"{path}: `{name}` observation table covers {expected} of {n_obs} values"
        )
    return block


def _duration(seconds: float) -> str:
    for unit, size in (("days", 86400), ("h", 3600), ("min", 60)):
        if seconds >= 2 * size:
            return f"{seconds / size:.3g} {unit}"
    return f"{seconds:g} s"


def _env_module(spec):
    package = type(spec.make_env()).__module__.rsplit(".", 1)[0]
    try:
        return importlib.import_module(package + ".env")
    except ModuleNotFoundError:
        return None


def _action_labels(env, n: int) -> list[str]:
    """Action meanings, where the environment's own docstring states them.

    Several class docstrings carry a line like
    ``Action  (2): [fuel, feedwater], raw in [-1, 1]``. That is the only place
    the meanings are written down, so it is the only honest source for them --
    inventing labels here would put words in the environment's mouth.
    """
    doc = type(env).__doc__ or ""
    for line in doc.splitlines():
        if "ction" not in line or "):" not in line:
            continue
        # Everything after the arity marker. Two spellings are in use and both
        # are read here: the bracketed list the aircraft carry,
        #   Action (3,): [power, stick, aileron] each in [-1, 1]
        # and the prose form the process plants carry,
        #   Action (1,): base flow, raw in [-1, 1] -> [q3_min, q3_max]
        # The earlier version took the first "[" on the line, which on the
        # second spelling is the *range* -- so it read "-1, 1" as two labels,
        # matched no single-action environment, and left eleven of twenty-two
        # pages with a blank meaning column.
        text = line.split("):", 1)[1].strip()
        for cut in (", raw in", " raw in", " each in", "->"):
            at = text.find(cut)
            if at >= 0:
                text = text[:at]
        text = text.strip().rstrip(",").strip()
        if text.startswith("["):
            stop = text.find("]")
            if stop < 0:
                continue
            text = text[1:stop]
        parts = [x.strip() for x in text.split(",") if x.strip()]
        if len(parts) == n:
            return parts
    return []


def _space_table(space, labels: list[str]) -> str:
    low = np.broadcast_to(np.asarray(space.low, float), space.shape or (1,))
    high = np.broadcast_to(np.asarray(space.high, float), space.shape or (1,))
    rows = ["| # | meaning | min | max |", "|---|---|---|---|"]
    for i, (lo, hi) in enumerate(zip(low, high)):
        rows.append(
            f"| {i} | {labels[i] if i < len(labels) else ''} | {lo:g} | {hi:g} |"
        )
    return "\n".join(rows)


def _obs_table(space, rows: list[tuple[int, int, str]]) -> str:
    # Every observation space in the suite spans the float32 range, which the
    # page says once; a space with real bounds needs them shown here first.
    for edge in (space.low, space.high):
        if np.any(np.abs(np.asarray(edge, float)) < 1e38):
            raise SystemExit("an observation space declares bounds; show them")
    out = ["| # | meaning |", "|---|---|"]
    for first, last, meaning in rows:
        out.append(f"| {first if first == last else f'{first}-{last}'} | {meaning} |")
    return "\n".join(out)


def _params_table(params) -> str:
    units = param_units(type(params))
    fields = [
        (k, v)
        for k, v in vars(params).items()
        if isinstance(v, (int, float)) and not isinstance(v, bool)
    ]
    missing = [k for k, _ in fields if k not in units]
    if missing:
        raise ValueError(f"{type(params).__name__}: no PARAM_UNITS entry for {missing}")
    rows = ["| parameter | value | unit |", "|---|---|---|"]
    for k, v in fields:
        value = f"{v:g}" if isinstance(v, float) else f"{v}"
        rows.append(f"| `{k}` | {value} | {units[k]} |")
    return "\n".join(rows)


def _baseline_section(spec, row: dict | None) -> str:
    if not spec.has_pid:
        return f"No baseline ships for this environment. {spec.baselines_note or ''}".strip()
    lines = []
    if row and row.get("pid_returns"):
        # Reported the way docs/baseline-results.md reports them: every reward is
        # minus a sum of costs, so the mean return is negative and the cost
        # per step is its positive counterpart. Four significant figures
        # because the plants span ten orders of magnitude; a fixed ``.1f``
        # printed the wind turbine's -0.0145 as -0.0.
        pid = np.asarray(row["pid_returns"], dtype=float)
        steps = int(row["steps"])
        lines.append(
            f"Recorded over {row['seeds']} seeds of the {steps}-step episode "
            "(see [Baseline results](../baseline-results.md)). The reward is a cost, so a "
            "return closer to zero is better.\n"
        )
        lines.append("| controller | mean return | cost per step |")
        lines.append("|---|---|---|")
        lines.append(f"| PID | {pid.mean():.4g} | {-pid.mean() / steps:.4g} |")
        if row.get("mpc_returns"):
            mpc = np.asarray(row["mpc_returns"], dtype=float)
            lines.append(f"| MPC | {mpc.mean():.4g} | {-mpc.mean() / steps:.4g} |")
            won = int((mpc > pid).sum())
            summary = f"\nThe MPC beats the PID on {won} of {len(pid)} seeds"
            trips = row.get("mpc_trips")
            if trips == 0:
                summary += " and does not trip the plant on any of them"
            elif trips is not None:
                summary += (
                    f" and trips the plant {trips} time{'' if trips == 1 else 's'}"
                    " across them"
                )
            lines.append(summary + ".")
        # A note on a task that ships both baselines says what one of them
        # is (patrol_bearing_only's MPC is a full-state bound), so it stays
        # beside the numbers it qualifies.
        if spec.baselines_note:
            lines.append(f"\n{spec.baselines_note}")
    elif spec.has_mpc:
        lines.append(
            "A PID and an MPC ship with this environment, but no comparison has "
            "been recorded for them yet."
        )
    else:
        # ``scripts/record_baselines.py`` only records environments with both
        # controllers, so a PID on its own never has numbers to show here. The
        # note says what the PID is and why no MPC ships.
        lines.append(
            "No MPC ships with this environment, so there is no recorded "
            f"comparison. {spec.baselines_note or 'A PID ships.'}"
        )
    # Both degradation notes are surfaced, not just the MPC's. The homepage
    # promises that "where a baseline is weak, the docs say how weak", and a
    # weak *expert* is the case that misleads hardest: a reader who beats it
    # concludes they beat a tuned controller. Rendered in full rather than
    # truncated at the first period -- these notes carry the measured numbers
    # that make the gap checkable, and the first sentence alone drops them.
    if spec.expert_degraded:
        lines.append(
            f'\n!!! warning "The shipped expert is weak here"\n'
            f"    {spec.expert_degraded}"
        )
    if spec.mpc_degraded:
        lines.append(
            f'\n!!! warning "The MPC is not an upper bound here"\n'
            f"    {spec.mpc_degraded.split('.')[0]}."
        )
    return "\n".join(lines)


def page(name: str, spec, recorded: dict) -> tuple[str, str]:
    env = spec.make_env()
    params = spec.make_test_params()
    # The Rewards and Episode end sections below describe the version-2
    # reward. Refuse to put that text on a page whose environment scores
    # differently, which is how "bounded in [0, 1]" outlived version 1.
    if getattr(params, "reward_version", 2) != 2:
        raise SystemExit(
            f"{name}: reward_version {params.reward_version}, and the page "
            "template describes version 2"
        )
    key = jax.random.PRNGKey(0)
    obs, state = env.reset_env(key, params)
    module = _env_module(spec)

    obs_space = env.observation_space(params)
    act_space = env.action_space(params)
    n_obs = int(np.prod(obs_space.shape or (1,)))
    tracked = env.obs_value_index
    tracked = tracked if isinstance(tracked, tuple) else (tracked,)
    targets = env.obs_target_index
    targets = targets if isinstance(targets, tuple) else (targets,)
    block = _task_block(name, env, n_obs)

    from target_gym.runners.runners import _tracked_labels

    try:
        labels = _tracked_labels(env, len(tracked))
    except Exception:
        labels = []

    title = display_name(name)
    video = _video(name)
    from target_gym.registry import control_step_seconds

    dt = control_step_seconds(env, params)
    episode = int(params.max_steps_in_episode)

    out = [f"# {title}", ""]
    if video:
        out += [
            # ``../../``, not ``../``.
            #
            # mkdocs serves these with directory URLs, so this page is
            # ``/environments/<name>/`` and a relative source resolves against
            # that directory, not against ``/environments/``. With one level the
            # browser asked for ``/environments/videos/<name>/pid_output.gif``
            # and got a 404 on every environment page, while the homepage
            # worked because it sits at the site root. mkdocs rewrites relative
            # links in Markdown but not inside raw HTML, which is why this has
            # to be right here.
            f'<p align="center"><img src="../../{video}" width="480px"/></p>',
            "",
        ]
    out += [
        block["summary"],
        "",
        "```python",
        "import target_gym as tg",
        "",
        f'env, params = tg.make("{name}")',
        "```",
        "",
        "| | |",
        "|---|---|",
        f"| Action space | `Box({act_space.shape or (1,)})`, all actions in [-1, 1] |",
        f"| Observation space | `Box({obs_space.shape or (1,)})` |",
        f"| Tracked variable(s) | {', '.join(labels) if labels else 'see below'} |",
        f"| Episode length | {episode} steps of {dt:g} s ({_duration(episode * dt)}) |",
        f"| Cite as | `{spec.versioned_name}` |",
        f"| Physics | [contract]({BLOB}/{physics_path(env).as_posix()}) |",
        "",
        "## Action space",
        "",
        "Actions are normalised to `[-1, 1]` and mapped onto the plant's real",
        "actuator range inside the environment.",
        "",
        _space_table(
            act_space, _action_labels(env, act_space.shape[0] if act_space.shape else 1)
        ),
        "",
        "## Observation space",
        "",
        f"{n_obs} values in the plant's own units. The space declares no bounds "
        "(it spans the float32 range), so scale them before training. The reward "
        "scores "
        + ", ".join(f"`obs[{v}]` against `obs[{t}]`" for v, t in zip(tracked, targets))
        + ".",
        "",
        _obs_table(obs_space, block["obs"]),
        "",
        "## Rewards",
        "",
    ]
    reward_doc = _first_paragraph(
        getattr(module, "compute_reward", None).__doc__
        if module and hasattr(module, "compute_reward")
        else None
    )
    out += [
        reward_doc or "See the environment's `compute_reward`.",
        "",
        "Every environment in this suite scores on one contract. The reward is",
        "minus the sum of three non-negative costs,",
        "`-(tracking_cost + running_cost + failure_cost)`. The running cost",
        "charges consumption and the failure cost charges trips out of the",
        "operating envelope. The reward is never positive, and its scale differs",
        "by orders of magnitude between plants. Some plants are",
        "priced in dollars or euros and the rest are dimensionless; the",
        "[per-plant summary](../reward-shaping.md#per-plant-summary) says which.",
        "See [Reward shaping](../reward-shaping.md) for how each cost is built.",
        "",
        "## Starting state",
        "",
        f"`reset` samples the initial condition and the target; state has "
        f"{len(state.__dataclass_fields__)} fields.",
        "",
        "## Episode end",
        "",
    ]
    term_doc = _first_paragraph(
        getattr(module, "check_is_terminal", None).__doc__
        if module and hasattr(module, "check_is_terminal")
        else None
    )
    # A trip restarts the plant, and ends the episode only with
    # ``continuing = False`` (``base.failure_kernel``), so ``check_is_terminal``
    # is the trip condition and its docstring, where there is one, says what trips.
    if getattr(params, "restart_in_place", False):
        trip = (
            "**Termination.** None. `terminated` is always false: the plant "
            "keeps its state through a trip instead of restarting, and every "
            "step spent outside the envelope is charged the trip cost and sets "
            '`info["tripped"]` and `info["trip_cost"]` until the controller '
            "brings it back."
        )
    else:
        trip = (
            "**Termination.** None by default. Leaving the operating envelope "
            "trips the plant: the step that leaves it is charged the trip cost "
            'and sets `info["tripped"]` and `info["trip_cost"]`, and the plant '
            "restarts as `reset_env` would while the episode clock keeps "
            "running. Episodic use is optional: with `continuing = False` the "
            "plant is lost and `terminated` is raised on that step instead."
        )
    out += [
        trip
        + (f" {term_doc}" if term_doc else "")
        + " See [Reward shaping](../reward-shaping.md#failure).",
        "",
        f"**Truncation.** After {episode} steps.",
        "",
        "## Baselines",
        "",
        _baseline_section(spec, recorded.get(name)),
        "",
        "## Arguments",
        "",
        "The scored configuration, which `tg.make` returns. A keyword argument "
        f'changes one field, as in `tg.make("{name}", max_steps_in_episode=...)`.',
        "",
        _params_table(params),
        "",
    ]
    row = (
        f"| [{title}](environments/{name}.md) | `{name}` | "
        f"{_first_sentence(block['summary'])} | {n_obs} | "
        f"{int(np.prod(act_space.shape or (1,)))} | "
        f"{episode} steps, {_duration(episode * dt)} |"
    )
    return "\n".join(out) + "\n", row


def _first_sentence(text: str) -> str:
    return re.split(r"(?<=[.!?])\s+(?=[A-Z`])", text, maxsplit=1)[0]


def _chooser(rows: dict[str, str]) -> str:
    """``docs/complexity.md`` with its table of every task rebuilt."""
    text = CHOOSER.read_text()
    if CHOOSER_BEGIN not in text or CHOOSER_END not in text:
        raise SystemExit(f"{CHOOSER}: the generated-table markers are missing")
    head, rest = text.split(CHOOSER_BEGIN, 1)
    tail = rest.split(CHOOSER_END, 1)[1]
    table = []
    for group, title in GROUPS.items():
        names = [n for n, s in REGISTRY.items() if s.group == group]
        if names:
            table += [
                f"### {title}",
                "",
                "| Task | Name | What it asks | Obs | Act | Episode |",
                "|---|---|---|---|---|---|",
                *(rows[n] for n in names),
                "",
            ]
    return f"{head}{CHOOSER_BEGIN}\n\n" + "\n".join(table) + f"{CHOOSER_END}{tail}"


def build() -> dict[pathlib.Path, str]:
    """Every generated file and its content: one page per task, and the chooser."""
    recorded = load_recorded_baselines()
    if not recorded:
        raise SystemExit(f"no recorded baselines in {BASELINES_PATH}")
    files, rows = {}, {}
    for name, spec in REGISTRY.items():
        files[OUT_DIR / f"{name}.md"], rows[name] = page(name, spec, recorded)
    files[CHOOSER] = _chooser(rows)
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if any page is stale")
    args = ap.parse_args()

    files = build()
    if args.check:
        stale = [
            path.relative_to(ROOT).as_posix()
            for path, content in files.items()
            if not path.exists() or path.read_text() != content
        ]
        if stale:
            print(f"stale generated pages: {stale}; run {__file__}")
            return 1
        print(f"{len(files)} generated pages are up to date")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in files.items():
        path.write_text(content)
    print(f"wrote {len(files)} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
